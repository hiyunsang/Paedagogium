def grade_prompt(theme, q, a, answer):
    clean = lambda s: re.sub(r"==(.+?)==", r"\1", s or "")
    return GRADE % {"theme": clean(theme), "q": clean(q), "a": clean(a), "answer": answer.strip()[:6000]}


def explain_prompt(n):
    g = lambda k: (n.get(k) or "").strip()[:3000] or "(없음)"
    return EXPLAIN % {"area": g("area"), "source": g("source"), "topic": g("topic"), "question": g("question"),
                      "my": g("myAnswer"), "right": g("correct"), "reason": g("reason")}


def title_of(question):
    t = re.sub(r"\s+", " ", question or "").strip()
    return (t[:38] + u"…") if len(t) > 40 else t
