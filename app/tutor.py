def ask_prompt(turns, question, mode="ask"):
    """지난 대화(최근 12개) + 새 물음. 시스템 프롬프트(TUTOR)는 따로 준다."""
    lines = []
    hist = [t for t in (turns or []) if t.get("content")][-12:]
    if hist:
        lines.append(u"[지난 대화]")
        for t in hist:
            who = u"수험생" if t.get("role") == "user" else u"튜터"
            lines.append(u"%s: %s" % (who, t.get("content", "")[:6000]))
        lines.append("")
    m = MODES.get(mode) or ""
    if m:
        lines.append(m)
        lines.append("")
    lines.append(u"[수험생의 물음]")
    lines.append(question.strip())
    return "\n".join(lines)


